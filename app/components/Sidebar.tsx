'use client';

import Link from 'next/link';
import { usePathname } from 'next/navigation';

const menuItems = [
  {
    section: 'Principal',
    items: [
      { label: 'Buscar Paciente', icon: SearchIcon, href: '/' },
      { label: 'Historial', icon: ClockIcon, disabled: true },
    ],
  },
  {
    section: 'Administración',
    items: [
      { label: 'Configuración PACS', icon: ServerIcon, disabled: true },
      { label: 'Usuarios', icon: UsersIcon, disabled: true },
      { label: 'Configuración', icon: SettingsIcon, disabled: true },
    ],
  },
];

export default function Sidebar() {
  const pathname = usePathname();
  return (
    <aside className="fixed left-0 top-0 h-screen w-64 bg-slate-900 text-white flex flex-col z-40">
      {/* Logo */}
      <div className="px-6 py-5 border-b border-slate-700">
        <div className="flex items-center gap-3">
          <div className="w-9 h-9 bg-blue-500 rounded-lg flex items-center justify-center">
            <HipIcon />
          </div>
          <div>
            <h1 className="text-lg font-bold tracking-tight">Hip-Pal</h1>
            <p className="text-[11px] text-slate-400">Análisis de Cadera</p>
          </div>
        </div>
      </div>

      {/* Navigation */}
      <nav className="flex-1 overflow-y-auto py-4 px-3">
        {menuItems.map((section) => (
          <div key={section.section} className="mb-6">
            <p className="px-3 mb-2 text-[11px] font-semibold uppercase tracking-wider text-slate-500">
              {section.section}
            </p>
            <ul className="space-y-1">
              {section.items.map((item) => {
                const activo = item.href === '/'
                  ? pathname === '/'
                  : !!item.href && pathname.startsWith(item.href);
                const clases = `w-full flex items-center gap-3 px-3 py-2 rounded-lg text-sm transition-colors ${
                  activo
                    ? 'bg-blue-600 text-white'
                    : item.disabled
                    ? 'text-slate-600 cursor-not-allowed'
                    : 'text-slate-300 hover:bg-slate-800 hover:text-white'
                }`;
                return (
                  <li key={item.label}>
                    {item.href ? (
                      <Link href={item.href} className={clases}>
                        <item.icon />
                        <span>{item.label}</span>
                      </Link>
                    ) : (
                      <button disabled={item.disabled} className={clases}>
                        <item.icon />
                        <span>{item.label}</span>
                        {item.disabled && (
                          <span className="ml-auto text-[10px] bg-slate-700 text-slate-400 px-1.5 py-0.5 rounded">
                            Próx.
                          </span>
                        )}
                      </button>
                    )}
                  </li>
                );
              })}
            </ul>
          </div>
        ))}
      </nav>

      {/* Footer */}
      <div className="px-4 py-4 border-t border-slate-700">
        <p className="text-[11px] text-slate-500 text-center">Hip-Pal v1.0</p>
      </div>
    </aside>
  );
}

